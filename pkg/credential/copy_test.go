// A derivation reads a claim as presented after an earlier one copied the
// claim's object and changed the copy.
func TestApplyDerivations_CopyLeavesItsSourceUnchanged(t *testing.T) {
	out, err := ApplyDerivations([]primitives.Derivation{
		{Copy: &primitives.CopyArgs{Input: claimpath.Keys("identity"), Output: claimpath.Keys("alias")}},
		{Lowercase: &primitives.LowercaseArgs{Input: claimpath.Keys("alias", "name")}},
		{Copy: &primitives.CopyArgs{Input: claimpath.Keys("identity", "name"), Output: claimpath.Keys("seen")}},
	}, map[string]any{"identity": map[string]any{"name": "ALICE"}}, time.Now(), nestedShapes)
	require.NoError(t, err)
	assert.Equal(t, map[string]any{"name": "alice"}, out["alias"])
	assert.Equal(t, "ALICE", out["seen"])
}

// A copy replaces an object already at its output path, in the pipeline and
// in the document the output is merged into.
func TestCopyReplacesAnExistingObject(t *testing.T) {
	list := []primitives.Derivation{
		{Copy: &primitives.CopyArgs{Input: claimpath.Keys("identity"), Output: claimpath.Keys("alias")}},
		{Copy: &primitives.CopyArgs{Input: claimpath.Keys("identity", "name"), Output: claimpath.Keys("nested", "alias_name")}},
	}
	claims := map[string]any{
		"identity": map[string]any{"name": "ALICE"},
		"alias":    map[string]any{"obsolete": "retained"},
		"nested":   map[string]any{"other": "kept", "alias_name": "old"},
	}

	out, replaced, err := ApplyDerivationsReplacing(list, claims, time.Now(), nil, nestedShapes)
	require.NoError(t, err)
	assert.Equal(t, map[string]any{"name": "ALICE"}, out["alias"])

	doc := CloneNestedClaims(claims)
	require.NoError(t, MergeDerived(doc, out, replaced))
	assert.Equal(t, map[string]any{"name": "ALICE"}, doc["alias"], "the obsolete field is gone")
	assert.Equal(t, map[string]any{"other": "kept", "alias_name": "ALICE"}, doc["nested"], "siblings of a leaf copy stay")
}

// A field a derivation generated stays generated after its object is copied,
// so reading it wrongly is a configuration fault, not the holder's input.
func TestACopiedObjectKeepsTheProvenanceOfItsFields(t *testing.T) {
	age := func(in claimpath.Pointer) primitives.Derivation {
		return primitives.Derivation{AgeOverThresholds: &primitives.AgeOverThresholdsArgs{Input: in, Thresholds: []int{18}}}
	}
	copyClaim := func(in, out claimpath.Pointer) primitives.Derivation {
		return primitives.Derivation{Copy: &primitives.CopyArgs{Input: in, Output: out}}
	}
	claims := map[string]any{"dob": "1990-01-15", "identity": map[string]any{"name": "x", "birthdate": "1990-01-15"}}
	ageOver18, birthdate := claimpath.Keys("age_over_18"), claimpath.Keys("identity", "birthdate")
	bd := claimpath.Keys("bd")

	for name, list := range map[string][]primitives.Derivation{
		"a leaf copy":    {age(claimpath.Keys("dob")), copyClaim(ageOver18, birthdate), copyClaim(birthdate, bd), age(bd)},
		"an object copy": {age(claimpath.Keys("dob")), copyClaim(ageOver18, birthdate), copyClaim(claimpath.Keys("identity"), claimpath.Keys("alias")), copyClaim(claimpath.Keys("alias", "birthdate"), bd), age(bd)},
	} {
		_, err := ApplyDerivations(list, claims, time.Now(), nestedShapes)
		require.Error(t, err, name)
		assert.NotErrorIs(t, err, primitives.ErrInvalidClaimInput, name)
		assert.Contains(t, err.Error(), "generated by an earlier derivation", name)
	}

	_, err := ApplyDerivations([]primitives.Derivation{copyClaim(claimpath.Keys("identity"), claimpath.Keys("alias")), copyClaim(claimpath.Keys("alias", "name"), claimpath.Keys("n")), age(claimpath.Keys("n"))},
		map[string]any{"identity": map[string]any{"name": "x"}}, time.Now(), nestedShapes)
	require.ErrorIs(t, err, primitives.ErrInvalidClaimInput, "a copied holder field is still the holder's input")
}

// A copy whose input is absent writes nothing, so it clears nothing, even
// when a later step writes under its output path.
func TestASkippedCopyClearsNothing(t *testing.T) {
	list := []primitives.Derivation{
		{Copy: &primitives.CopyArgs{Input: claimpath.Keys("missing"), Output: claimpath.Keys("identity")}},
		{Lowercase: &primitives.LowercaseArgs{Input: claimpath.Keys("identity", "name")}},
	}
	claims := map[string]any{"identity": map[string]any{"name": "ALICE", "country": "SE"}}

	out, replaced, err := ApplyDerivationsReplacing(list, claims, time.Now(), nil, nestedShapes)
	require.NoError(t, err)
	assert.Empty(t, replaced, "the copy wrote nothing")

	doc := CloneNestedClaims(claims)
	require.NoError(t, MergeDerived(doc, out, replaced))
	assert.Equal(t, map[string]any{"name": "alice", "country": "SE"}, doc["identity"])
}

// A derivation that writes into an element of an array of the claims, as
// a copy's output or in place, writes into the derivations' own copy: the
// caller's claims are unchanged. Merged into the document, the write lands
// in that element, and the other elements and fields stay.
func TestApplyDerivations_WriteIntoAnArrayElement(t *testing.T) {
	first := func(key string) claimpath.Pointer {
		return claimpath.New(claimpath.Key("items"), claimpath.Index(0), claimpath.Key(key))
	}
	for name, tc := range map[string]struct {
		derivation primitives.Derivation
		want       map[string]any
	}{
		"a copy": {
			derivation: primitives.Derivation{Copy: &primitives.CopyArgs{Input: claimpath.Keys("birthdate"), Output: first("name")}},
			want:       map[string]any{"name": "1996-01-30", "kind": "A"},
		},
		"in place": {
			derivation: primitives.Derivation{Lowercase: &primitives.LowercaseArgs{Input: first("kind")}},
			want:       map[string]any{"name": "first", "kind": "a"},
		},
	} {
		t.Run(name, func(t *testing.T) {
			given := func() map[string]any {
				return map[string]any{"birthdate": "1996-01-30", "items": []any{
					map[string]any{"name": "first", "kind": "A"},
					map[string]any{"name": "second"},
				}}
			}
			claims := given()
			out, replaced, err := ApplyDerivationsReplacing([]primitives.Derivation{tc.derivation}, claims, time.Now(), nil, nestedShapes)
			require.NoError(t, err)
			assert.Equal(t, given(), claims, "the caller's claims are unchanged")

			doc := CloneNestedClaims(claims)
			require.NoError(t, MergeDerived(doc, out, replaced))
			assert.Equal(t, []any{tc.want, map[string]any{"name": "second"}}, doc["items"])
			assert.Equal(t, "1996-01-30", doc["birthdate"])
		})
	}
}
